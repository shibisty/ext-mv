// Матрицы для камеры и проекции (column-major Float32).
export function mulCol(a: ArrayLike<number>, b: ArrayLike<number>): Float32Array {
  const o = new Float32Array(16);
  for (let c = 0; c < 4; c++) for (let r = 0; r < 4; r++) { let s = 0; for (let k = 0; k < 4; k++) s += a[k * 4 + r]! * b[c * 4 + k]!; o[c * 4 + r] = s; }
  return o;
}
export function perspective(fovy: number, asp: number, n: number, f: number): Float32Array {
  const t = 1 / Math.tan(fovy / 2), nf = 1 / (n - f);
  return new Float32Array([t / asp, 0, 0, 0, 0, t, 0, 0, 0, 0, (f + n) * nf, -1, 0, 0, 2 * f * n * nf, 0]);
}
export function lookAt(e: number[], c: number[], u: number[]): Float32Array {
  let zx = e[0]! - c[0]!, zy = e[1]! - c[1]!, zz = e[2]! - c[2]!, l = Math.hypot(zx, zy, zz) || 1;
  zx /= l; zy /= l; zz /= l;
  let xx = u[1]! * zz - u[2]! * zy, xy = u[2]! * zx - u[0]! * zz, xz = u[0]! * zy - u[1]! * zx;
  l = Math.hypot(xx, xy, xz) || 1;
  xx /= l; xy /= l; xz /= l;
  const yx = zy * xz - zz * xy, yy = zz * xx - zx * xz, yz = zx * xy - zy * xx;
  return new Float32Array([xx, yx, zx, 0, xy, yy, zy, 0, xz, yz, zz, 0, -(xx * e[0]! + xy * e[1]! + xz * e[2]!), -(yx * e[0]! + yy * e[1]! + yz * e[2]!), -(zx * e[0]! + zy * e[1]! + zz * e[2]!), 1]);
}
